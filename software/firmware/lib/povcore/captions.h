// =====================================================================================================================
//  captions.h - live-caption procedural mode of the POV LED Column v2 (first compiled and host-tested 2026-11-03).
//  A port of software/captions/column_model.py, which is the tested reference (software/tests/test_captions.py):
//  word mode (auto font, centred in the 32-column window, mini-scroll for long words) and ticker mode (hybrid: still
//  while words arrive, each new word jumps in; or the deadline-controlled crawl with the drop rule), plus the current
//  limiter. Fonts come from captions_font.h, generated by software/captions/font.py.
//
//  Threading on the ESP32: receive() runs in the WebSocket handler (core 0, async TCP task) and only queues the message
//  in a single-producer / single-consumer ring (no FreeRTOS objects, so the host tests can run the same code).
//  render() runs in the caption task: once per refresh tick (dt = the tick length: advance the animation, exactly
//  column_model.tick()) and right after a message arrives (dt = 0: apply the message and re-draw; in hybrid ticker mode
//  the new word jumps in now, nothing else moves). The caller stages the frame for the column task, which swaps it in
//  at the next tick boundary so all 24 strips change together.
//
//  Known, deliberate difference from the Python model on the device: a frame drawn on a message wake has the word's
//  tick counter at 0 where Python has 1 (same pixels while inside scroll_pause), so a long word's mini-scroll starts
//  one tick (33 ms) later than in the simulator. The host test replays messages tick by tick like Python and matches
//  pixel for pixel (test/test_captions).
// =====================================================================================================================
#pragma once
#include <ArduinoJson.h>

#include "pov_compat.h"
#include "captions_font.h"
#include "povframe.h"

namespace cap {

static const int ROWS = POV_ROWS, COLS = POV_COLS;
static const int WIN_C = 48, WIN_W = 32, WIN_L = WIN_C - WIN_W / 2, WIN_R = WIN_C + WIN_W / 2 - 1;

struct Cfg {
  uint8_t rgb[3] = {255, 214, 160};
  float dim = 0.30f;
  uint8_t word_vs = 2, tick_vs = 2;
  bool tick_7x9 = false;
  // camera legibility: smooth motion reads at <= 1 column per tick only; faster motion = discrete jumps
  bool scroll_jump = true; uint8_t scroll_jump_cols = 6, scroll_jump_ticks = 3;
  uint8_t scroll_cpt = 4, scroll_pause = 4;
  bool tick_hybrid = true; uint8_t crawl_cpt = 1; double crawl_idle_s = 1.5;   // hybrid ticker (default)
  double v_min = 40, v_max = 110, target_lag = 1.0, max_behind = 1.5;           // crawl ticker
  // the limiter counts LEDs + idle + ESP32 like column_model (fixed = 336 + 120 mA); CAP_MA is LEDs + idle only
  uint16_t cap_ma = (uint16_t)(pov::CAP_MA + pov::I_ESP_MA);
  uint8_t gb_max = 31, gb_release_ticks = 3;
};

enum MsgType : uint8_t { M_NONE, M_MODE, M_WORD, M_CLEAR, M_APPEND, M_PARTIAL };
struct Msg { MsgType type; uint8_t dim; uint8_t mode; uint32_t id; char text[48]; };

struct TapeWord { char text[48]; int32_t start; uint16_t width; double t_append; bool entered; uint32_t id; };
static const int MAX_TAPE = 32;   // words kept on the tape (the Python model keeps all; 64 columns past the window they are forgotten anyway)

// ---------------------------------------------------------------- font helpers
static inline const CapGlyph* glyph(char ch, bool big) {
  if (ch >= 'a' && ch <= 'z') ch -= 32;                // the engine sends UPPERCASE; /api/text may not
  if (ch < CAPF_FIRST || ch > CAPF_LAST) return nullptr;
  const CapGlyph* g = big ? &CAPF_7X9[ch - CAPF_FIRST] : &CAPF_5X7[ch - CAPF_FIRST];
  return g->w ? g : nullptr;
}

static inline int text_width(const char* s, bool big) {
  int w = 0, n = 0;
  for (; *s; s++) { const CapGlyph* g = glyph(*s, big); if (g) { w += g->w; n++; } }
  return n ? w + CAPF_GAP * (n - 1) : 0;
}

// Draw a string with its left edge at column col0 (may be outside 0..95), vertically centred, scaled vs.
// ticker: columns are taken mod 96 but only travel d = WIN_R - col in [-32, 64) is drawn (the whole drum once);
// otherwise clip_l..clip_r (inclusive) is the visible range.
static inline void draw_text(uint8_t* fr, const char* s, int col0, bool big, uint8_t vs, uint8_t ci,
                             int clip_l, int clip_r, bool ticker) {
  const int h = big ? CAPF_7X9_H : CAPF_5X7_H;
  const int base = (ROWS - h * vs) / 2;
  int c = col0, n = 0;
  for (; *s; s++) {
    const CapGlyph* g = glyph(*s, big);
    if (!g) continue;
    if (n++) c += CAPF_GAP;
    for (int x = 0; x < g->w; x++, c++) {
      int col = c;
      if (ticker) { int d = WIN_R - c; if (d < -32 || d >= 64) continue; col = ((c % COLS) + COLS) % COLS; }
      else if (c < clip_l || c > clip_r) continue;
      uint16_t bits = g->col[x];
      for (int i = 0; i < h; i++)
        if (bits & (1u << i)) {                        // bit 0 = top row; frame row 0 = bottom
          int r = base + (h - 1 - i) * vs;
          for (int k = 0; k < vs; k++) fr[(r + k) * COLS + col] = ci;
        }
    }
  }
}

// Marquee around the whole drum (the /api/text scroller). Like the ticker, glyph column u of the tape sits at drum
// column d = WIN_R - x + u: at x = 0 the text's first column is at the window's right edge and the rest is still
// round the back; as x grows the text moves to the viewer's left. The text repeats every `period` columns (>= 96,
// so one copy is on the drum at a time).
static inline void draw_text_marquee(uint8_t* fr, const char* s, int x, int period, bool big, uint8_t vs, uint8_t ci) {
  int w = text_width(s, big);
  if (w <= 0 || period <= 0) return;
  // one pass over the drum: drum column d shows tape column u = (x + d - WIN_R) mod period
  for (int d = 0; d < COLS; d++) {
    int u = (x + d - WIN_R) % period;
    if (u < 0) u += period;
    if (u >= w) continue;
    // draw the string at col0 = d - u so that its column u lands on d, clipped to d only
    draw_text(fr, s, d - u, big, vs, ci, d, d, false);
  }
}

// ---------------------------------------------------------------- the mode
class Captions {
 public:
  Cfg cfg;
  bool tick_mode = false;
  double t = 0;
  uint8_t gb = 31;                      // current field after the limiter (palette rebuilt by the caller when it changes)
  double peak_ma = 0;
  uint32_t dropped = 0;
  uint32_t applied_ids[8]; uint8_t n_applied = 0;   // ids applied in the last render (acked after the swap)
  // read-only views for the tests and the status page
  double x_pos() const { return x; }
  double v_cps() const { return v; }
  int tape_len() const { return ntape; }
  const TapeWord* tape_at(int i) const { return (i >= 0 && i < ntape) ? &tape[i] : nullptr; }
  int32_t tape_end_col() const { return tape_end; }
  bool is_tick() const { return tick_mode; }

  void begin() { clear(); }

  // Producer side (WebSocket handler): parse + queue. Never draws.
  void receive(const char* json, size_t len) {
    JsonDocument d;
    if (deserializeJson(d, json, len)) return;
    const char* c = d["cap"] | "";
    Msg m = {}; m.id = d["id"] | 0;
    if (!strcmp(c, "mode")) { m.type = M_MODE; m.mode = !strcmp(d["m"] | "word", "tick"); }
    else if (!strcmp(c, "clear")) m.type = M_CLEAR;
    else if (!strcmp(c, "word")) { m.type = M_WORD; m.dim = d["dim"].as<int>() ? 1 : 0; pov::strlcpy_(m.text, d["w"] | "", sizeof m.text); }
    else if (!strcmp(c, "tick")) {
      if (d["append"].is<const char*>()) { m.type = M_APPEND; pov::strlcpy_(m.text, d["append"], sizeof m.text); push(m); }
      if (d["partial"].is<const char*>()) { Msg p = {}; p.type = M_PARTIAL; pov::strlcpy_(p.text, d["partial"], sizeof p.text); push(p); }
      return;
    } else if (!strcmp(c, "cfg")) {
      if (d["rgb"].is<JsonArray>()) for (int i = 0; i < 3; i++) cfg.rgb[i] = (uint8_t)(d["rgb"][i] | (int)cfg.rgb[i]);
      if (d["dim"].is<float>()) cfg.dim = d["dim"].as<float>();
      if (d["word_vs"].is<int>()) cfg.word_vs = (uint8_t)pov::clampv(d["word_vs"].as<int>(), 1, 4);
      if (d["tick_vs"].is<int>()) cfg.tick_vs = (uint8_t)pov::clampv(d["tick_vs"].as<int>(), 1, 4);
      if (d["tick_font"].is<const char*>()) cfg.tick_7x9 = strcmp(d["tick_font"].as<const char*>(), "7x9") == 0;
      if (d["v_min"].is<float>()) cfg.v_min = d["v_min"].as<float>();
      if (d["v_max"].is<float>()) cfg.v_max = d["v_max"].as<float>();
      if (d["target_lag"].is<float>()) cfg.target_lag = d["target_lag"].as<float>();
      if (d["max_behind"].is<float>()) cfg.max_behind = d["max_behind"].as<float>();
      if (d["crawl_idle_s"].is<float>()) cfg.crawl_idle_s = d["crawl_idle_s"].as<float>();
      if (d["crawl_cpt"].is<int>()) cfg.crawl_cpt = (uint8_t)pov::clampv(d["crawl_cpt"].as<int>(), 0, 12);
      if (d["scroll_jump_cols"].is<int>()) cfg.scroll_jump_cols = (uint8_t)pov::clampv(d["scroll_jump_cols"].as<int>(), 1, 32);
      if (d["scroll_jump_ticks"].is<int>()) cfg.scroll_jump_ticks = (uint8_t)pov::clampv(d["scroll_jump_ticks"].as<int>(), 1, 30);
      if (d["scroll_cpt"].is<int>()) cfg.scroll_cpt = (uint8_t)pov::clampv(d["scroll_cpt"].as<int>(), 1, 32);
      if (d["scroll_pause"].is<int>()) cfg.scroll_pause = (uint8_t)pov::clampv(d["scroll_pause"].as<int>(), 0, 60);
      if (d["tick_style"].is<const char*>()) cfg.tick_hybrid = strcmp(d["tick_style"].as<const char*>(), "crawl") != 0;
      if (d["scroll_style"].is<const char*>()) cfg.scroll_jump = strcmp(d["scroll_style"].as<const char*>(), "smooth") != 0;
      if (d["gb_max"].is<int>()) cfg.gb_max = (uint8_t)pov::clampv(d["gb_max"].as<int>(), 1, 31);
      if (d["cap_ma"].is<int>()) cfg.cap_ma = (uint16_t)pov::clampv(d["cap_ma"].as<int>(), 500, 6000);
      if (d["gb_release_ticks"].is<int>()) cfg.gb_release_ticks = (uint8_t)pov::clampv(d["gb_release_ticks"].as<int>(), 1, 30);
      return;
    } else return;
    push(m);
  }

  // Consumer side (caption task). dt > 0: one refresh tick has passed (column_model.tick). dt == 0: a message arrived,
  // apply it and re-draw the same tick. Draws ROWS*COLS palette indices into fr: 0 off, 1 caption colour, 2 dim.
  void render(double now, double dt, uint8_t* fr) {
    t = now;
    n_applied = 0;
    Msg m;
    while (pop(m)) apply(m);
    if (tick_mode) { if (dt > 0 || cfg.tick_hybrid) ticker_step(dt, dt > 0); }
    else if (dt > 0) word_ticks++;
    memset(fr, 0, ROWS * COLS);
    if (!tick_mode && word[0]) draw_word(fr);
    if (tick_mode) {
      bool big = cfg.tick_7x9;
      for (int i = 0; i < ntape; i++)
        draw_text(fr, tape[i].text, (int)floor(WIN_R - (x - tape[i].start)), big, cfg.tick_vs, 1, 0, COLS - 1, true);
      if (partial[0]) {
        double pend = std::max((double)tape_end, ceil(x));
        draw_text(fr, partial, (int)floor(WIN_R - (x - pend)), big, cfg.tick_vs, 2, 0, COLS - 1, true);
      }
    }
    limit(fr, dt > 0);
  }

  // The three palette entries the frame uses, in sRGB (what column_model.Config.palette() returns: dim is truncated)
  void palette_rgb(uint8_t out[3][3]) const {
    for (int c = 0; c < 3; c++) { out[0][c] = 0; out[1][c] = cfg.rgb[c]; out[2][c] = (uint8_t)(cfg.rgb[c] * cfg.dim); }
  }

 private:
  // single-producer / single-consumer ring: receive() writes, render() reads
  static const int QN = 16;
  Msg q[QN];
  volatile uint8_t qh = 0, qt = 0;
  char word[48] = ""; bool word_dim = false; uint32_t word_ticks = 0;
  TapeWord tape[MAX_TAPE]; int ntape = 0; int32_t tape_end = 0; double x = 0, v = 0;
  char partial[48] = "";
  uint8_t rel = 0;
  double last_append = -1e9;

  void push(const Msg& m) {
    uint8_t h = qh, n = (uint8_t)((h + 1) % QN);
    if (n == qt) return;                       // full: drop (the next word replaces it anyway)
    q[h] = m;
    __asm__ __volatile__("" ::: "memory");
    qh = n;
  }
  bool pop(Msg& m) {
    uint8_t tt = qt;
    if (tt == qh) return false;
    m = q[tt];
    __asm__ __volatile__("" ::: "memory");
    qt = (uint8_t)((tt + 1) % QN);
    return true;
  }
  void clear() { word[0] = 0; word_dim = false; word_ticks = 0; ntape = 0; tape_end = 0; x = 0; v = 0; partial[0] = 0; }
  int sep() const { return text_width(" ", cfg.tick_7x9) + 1; }

  void apply(const Msg& m) {
    switch (m.type) {
      case M_MODE: tick_mode = m.mode; clear(); break;
      case M_CLEAR: clear(); break;
      case M_WORD: pov::strlcpy_(word, m.text, sizeof word); word_dim = m.dim; word_ticks = 0; break;
      case M_PARTIAL: pov::strlcpy_(partial, m.text, sizeof partial); break;
      case M_APPEND: append(m.text, m.id); break;
      default: break;
    }
    if (m.id && n_applied < 8 && !m.dim) applied_ids[n_applied++] = m.id;
  }

  void append(const char* text, uint32_t id) {
    char buf[48]; pov::strlcpy_(buf, text, sizeof buf);
    char* save = nullptr;
    for (char* w = strtok_r(buf, " \t\r\n", &save); w; w = strtok_r(nullptr, " \t\r\n", &save)) {
      if (ntape == MAX_TAPE) { memmove(&tape[0], &tape[1], sizeof(TapeWord) * (MAX_TAPE - 1)); ntape--; }
      TapeWord& tw = tape[ntape++];
      pov::strlcpy_(tw.text, w, sizeof tw.text);
      tw.width = (uint16_t)text_width(tw.text, cfg.tick_7x9);
      tw.start = tape_end < x ? (int32_t)ceil(x) : tape_end;   // the tape ran dry: start entering now
      tw.t_append = t; tw.entered = false; tw.id = id;
      tape_end = tw.start + tw.width + sep();
      last_append = t;
    }
  }

  double need(double lag, double dt) const {
    double v_need = 0;
    bool first = true;
    for (int i = 0; i < ntape; i++) {
      if (tape[i].entered) continue;
      double left = std::max(tape[i].t_append + lag - t + dt, dt);
      double vn = (tape[i].start + tape[i].width - x) / left;
      if (first || vn > v_need) { v_need = vn; first = false; }
    }
    return v_need;
  }

  void mark_entered() {
    for (int i = 0; i < ntape; i++)
      if (!tape[i].entered && x >= tape[i].start + tape[i].width) tape[i].entered = true;
  }

  void forget_old() {             // words 64 columns past the window's right edge are behind the drum: forget them
    int k = 0;
    for (int i = 0; i < ntape; i++) if (x - (tape[i].start + tape[i].width) < 64) tape[k++] = tape[i];
    ntape = k;
  }

  // allow_drift = this is a real tick (dt > 0); on a message re-render only the hybrid jump happens
  void ticker_step(double dt, bool allow_drift) {
    int waiting = 0, newest = -1;
    for (int i = 0; i < ntape; i++) if (!tape[i].entered) { waiting++; newest = i; }
    if (cfg.tick_hybrid) {        // still while words arrive (each jumps fully in); drift away once idle
      int step = 0;
      if (waiting) step = std::max(0, (int)ceil(tape[newest].start + tape[newest].width - x));
      else if (allow_drift && ntape && t - last_append >= cfg.crawl_idle_s) step = cfg.crawl_cpt;
      v = dt > 0 ? step / dt : 0;
      x += step;
      mark_entered();
      forget_old();
      return;
    }
    if (!allow_drift) return;     // crawl: nothing moves between ticks
    // drop rule: if even v_max misses the hard deadline, drop the oldest word that has not started to enter
    while (waiting > 1 && need(cfg.max_behind, dt) > cfg.v_max) {
      int d = -1;
      for (int i = 0; i < ntape; i++) if (!tape[i].entered && tape[i].start >= x && i != newest) { d = i; break; }
      if (d < 0) break;
      int gap = tape[d].width + sep();
      for (int i = d + 1; i < ntape; i++) tape[i].start -= gap;
      memmove(&tape[d], &tape[d + 1], sizeof(TapeWord) * (ntape - d - 1));
      ntape--; newest--; waiting--; tape_end -= gap; dropped++;
    }
    if (waiting) v = std::min(cfg.v_max, std::max(cfg.v_min, need(cfg.target_lag, dt)));
    else v = ntape ? cfg.v_min : 0;
    x += v * dt;
    mark_entered();
    forget_old();
  }

  void draw_word(uint8_t* fr) {
    bool big = text_width(word, true) <= WIN_W;
    int w = text_width(word, big);
    uint8_t ci = word_dim ? 2 : 1;
    if (w <= WIN_W) { draw_text(fr, word, WIN_C - w / 2, big, cfg.word_vs, ci, 0, COLS - 1, false); return; }
    int k = std::max(0, (int)word_ticks - (int)cfg.scroll_pause);          // mini-scroll in 5x7
    int off = cfg.scroll_jump ? (k / cfg.scroll_jump_ticks) * cfg.scroll_jump_cols : k * cfg.scroll_cpt;
    off = std::min(w - WIN_W, off);
    draw_text(fr, word, WIN_L - off, false, cfg.word_vs, ci, WIN_L - 8, WIN_R + 8, false);
  }

  // current limiter (same model as povanim.current_profile): worst of the 96 rotor positions at gb 31, then the
  // largest gb that keeps it under cap_ma; drop at once, recover 1 step every gb_release_ticks ticks. ~32k lookups.
  void limit(const uint8_t* fr, bool is_tick) {
    uint8_t pal[3][3];
    palette_rgb(pal);
    double ich[3];                                    // mA per LED at gb 31 for palette index 0/1/2
    for (int p = 0; p < 3; p++) {
      double s = 0;
      for (int c = 0; c < 3; c++) s += pow(pal[p][c] / 255.0, 2.2) * 20.0;
      ich[p] = s;
    }
    double worst = 0;
    for (int col = 0; col < COLS; col++) {
      double sum = 0;
      for (int ch = 0; ch < POV_CHAINS; ch++)
        for (int k = 0; k < POV_LEDS_PER_CHAIN; k++) {
          int c = col + POV_LED_COLOFF[ch][k];
          if (c >= COLS) c -= COLS;
          sum += ich[fr[POV_LED_ROW[ch][k] * COLS + c]];
        }
      if (sum > worst) worst = sum;
    }
    const double fixed = (double)pov::IDLE_MA + (double)pov::I_ESP_MA;
    int fit = worst <= 0 ? cfg.gb_max : (int)std::min((double)cfg.gb_max, 31.0 * (cfg.cap_ma - fixed) / worst);
    fit = std::max(1, fit);
    if (fit < gb) { gb = (uint8_t)fit; rel = 0; }
    else if (fit > gb && is_tick) { if (++rel >= cfg.gb_release_ticks) { gb++; rel = 0; } }
    peak_ma = fixed + worst * gb / 31.0;
  }
};

}  // namespace cap
