"""Generate the firmware's gamma table and the host-test vectors from the Python reference code.

    py software/firmware/test/gen_vectors.py          (run from the repo root; needs numpy, like the rest of software/)

Writes (all committed, regenerate when povanim.py / font.py / column_model.py change):
    lib/povcore/povgamma.h        POV_GAMMA22[256] = povanim.gamma_lut()
    test/vectors/vec_povmap.h     column_indices() for four columns of a known frame (the firmware's build_column must agree)
    test/vectors/vec_current.h    current_profile() worst cases for three frames (the firmware's current model must agree)
    test/vectors/vec_pova.h       the dog animation file bytes + its decoded first and last frames (pova.h must agree)
    test/vectors/vec_font.h       text widths and layout_word() results for a word list (captions.h fonts must agree)
    test/vectors/vec_captions.h   scripted caption sessions: messages per tick + the frame ColumnCaptions drew at every tick
                                  (captions.h must draw the same 42 x 96 frame, pixel for pixel)

Frames are stored RLE (run u8, index u8), row-major, row 0 = bottom, exactly like a .pova frame.
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
SW = os.path.dirname(FW)
sys.path.insert(0, os.path.join(SW, "povgen"))
sys.path.insert(0, os.path.join(SW, "captions"))

import numpy as np  # noqa: E402

import povanim as pa  # noqa: E402
import font  # noqa: E402
from column_model import ColumnCaptions, Config, TICK_HZ, layout_word  # noqa: E402

TICK = 1.0 / TICK_HZ
VEC = os.path.join(HERE, "vectors")
HEAD = "// Generated by software/firmware/test/gen_vectors.py from the Python reference code - do not edit by hand.\n#pragma once\n#include <stdint.h>\n"


def c_array(name, data, ctype="uint8_t", per_line=24, fmt=str):
    data = list(data)
    lines = [f"static const {ctype} {name}[{len(data)}] = {{"]
    for i in range(0, len(data), per_line):
        lines.append("  " + ", ".join(fmt(v) for v in data[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rle(frame) -> bytes:
    return pa.rle_encode(np.asarray(frame, dtype=np.uint8).ravel())


def rle_block(name, frames):
    """Concatenated RLE frames + offsets (n + 1 entries)."""
    blob, offs = bytearray(), [0]
    for f in frames:
        blob += rle(f)
        offs.append(len(blob))
    return c_array(name + "_RLE", blob) + c_array(name + "_RLE_OFF", offs, "uint32_t", 16)


def write(name, text):
    os.makedirs(VEC, exist_ok=True)
    path = os.path.join(VEC, name) if name.endswith(".h") and not name.startswith("..") else name
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, FW), len(text), "bytes")


# ---------------------------------------------------------------- gamma table (lib/povcore/povgamma.h)
def gen_gamma():
    lut = pa.gamma_lut()
    text = ("// Generated by software/firmware/test/gen_vectors.py (povanim.gamma_lut, gamma 2.2) - do not edit by hand.\n"
            "// sRGB 8-bit -> SK9822 8-bit PWM duty: round(255 * (v/255)^2.2). The 5-bit current field is applied separately.\n"
            "#pragma once\n#include <stdint.h>\n" + c_array("POV_GAMMA22", lut, per_line=16))
    write(os.path.join(FW, "lib", "povcore", "povgamma.h"), text)


# ---------------------------------------------------------------- LED mapping vectors
def test_frame():
    f = np.arange(pa.ROWS * pa.COLS, dtype=np.int32).reshape(pa.ROWS, pa.COLS) % 251
    return f.astype(np.uint8)


def gen_povmap():
    cols = [0, 7, 48, 95]
    f = test_frame()
    text = HEAD + "// frame[r][c] = (r * 96 + c) % 251; VEC_MAP_COL_<i>[chain * 168 + pos] = povanim.column_indices(frame, col)\n"
    text += c_array("VEC_MAP_COLS", cols, "int", 8)
    for i, c in enumerate(cols):
        text += c_array(f"VEC_MAP_COL_{i}", pa.column_indices(f, c).ravel())
    write("vec_povmap.h", text)


# ---------------------------------------------------------------- current model vectors
def gen_current(dog: pa.Animation):
    pal_bw = np.array([[0, 0, 0], [255, 255, 255]], dtype=np.uint8)
    on = np.ones((pa.ROWS, pa.COLS), np.uint8)
    diag = np.zeros((pa.ROWS, pa.COLS), np.uint8)
    for r in range(pa.ROWS):
        diag[r, (r * 2) % pa.COLS] = 1
        diag[r, (r * 2 + 48) % pa.COLS] = 1
    pal_dog = dog.palette.array()
    cases = [("ALLWHITE_GB31", on, pal_bw, 31), ("ALLWHITE_GB15", on, pal_bw, 15), ("DIAG_GB31", diag, pal_bw, 31),
             ("DOG0_GB31", dog.frames[0], pal_dog, 31), ("DOG0_GB8", dog.frames[0], pal_dog, 8)]
    text = HEAD + "// povanim.current_profile(frame, palette, gb).max() in mA: LED drive + 336 x 1 mA idle + 120 mA ESP32\n"
    for name, fr, pal, gb in cases:
        prof = pa.current_profile(fr, pal, gb)
        text += f"static const double VEC_CUR_{name}_MAX = {prof.max():.4f};\n"
        text += f"static const double VEC_CUR_{name}_MIN = {prof.min():.4f};\n"
    text += f"static const double VEC_CUR_FIXED_MA = {pa.N_STRIPS * pa.LEDS_PER_STRIP * pa.I_DARK_MA + pa.I_ESP_MA:.1f};\n"
    text += f"static const double VEC_CAP_MA = {pa.CAP_MA:.1f};\n"
    text += c_array("VEC_CUR_DIAG", diag.ravel())
    write("vec_current.h", text)


# ---------------------------------------------------------------- .pova vectors
def gen_pova(dog: pa.Animation, raw: bytes):
    text = HEAD + "// software/content/public/dog_ball_orbit.pova as bytes, plus what povanim decodes from it\n"
    text += c_array("VEC_DOG_POVA", raw)
    text += f"static const int VEC_DOG_NFRAMES = {dog.n};\n"
    text += f"static const int VEC_DOG_FPS_X10 = {int(round(dog.fps * 10))};\n"
    text += f"static const int VEC_DOG_NPAL = {len(dog.palette)};\n"
    text += f"static const int VEC_DOG_LOOP = {1 if dog.loop else 0};\n"
    text += f"static const char* const VEC_DOG_NAME = {c_str(dog.meta.get('name', ''))};\n"
    text += f"static const char* const VEC_DOG_SCOPE = {c_str(dog.meta.get('scope', ''))};\n"
    text += c_array("VEC_DOG_PAL", dog.palette.array().ravel())
    text += c_array("VEC_DOG_HOLDS", dog.holds)
    text += c_array("VEC_DOG_F0", dog.frames[0].ravel(), per_line=32)
    text += rle_block("VEC_DOG_FLAST", [dog.frames[-1]])
    write("vec_pova.h", text)


# ---------------------------------------------------------------- font vectors
WORDS = ["HI", "SO", "HELLO", "TRANSCRIPTION", "WWWWW", "F9", "IT'S", "3.5%", "A B", "CAPTIONS", "I", "WORD", "COLUMN",
         "!", "?", "=", "1234567890", "ABCDEFGHIJKLM", "NOPQRSTUVWXYZ", " ", "*", "A*B"]


def gen_font():
    text = HEAD + "// font.text_width / column_model.layout_word for VEC_FONT_WORDS (uppercase only; '*' is not drawn)\n"
    text += "static const char* const VEC_FONT_WORDS[] = {" + ", ".join(c_str(w) for w in WORDS) + "};\n"
    text += f"static const int VEC_FONT_N = {len(WORDS)};\n"
    text += c_array("VEC_FONT_W5", [font.text_width(w, "5x7") for w in WORDS], "int", 16)
    text += c_array("VEC_FONT_W7", [font.text_width(w, "7x9") for w in WORDS], "int", 16)
    text += c_array("VEC_FONT_BIG", [1 if layout_word(w)[0] == "7x9" else 0 for w in WORDS], "int", 16)
    text += c_array("VEC_FONT_SCROLL", [1 if layout_word(w)[2] else 0 for w in WORDS], "int", 16)
    # two rendered words, one per font, as frames (word mode draws them centred in the window, vs 2)
    frames = []
    for w in ("HI", "HELLO"):
        m = ColumnCaptions(mode="word")
        m.receive({"cap": "word", "w": w})
        frames.append(m.tick(0.0))
    text += rle_block("VEC_FONT_FRAMES", frames)
    write("vec_font.h", text)


# ---------------------------------------------------------------- caption sessions
def session(name, events, nticks, cfg=None, mode="word"):
    """events: {tick: [json dict, ...]}. Returns the C text for the session."""
    import json
    m = ColumnCaptions(cfg=cfg or Config(), mode=mode)
    frames, xs, gbs, peaks, vs, drops, modes = [], [], [], [], [], [], []
    ev_lines = []
    for k in range(nticks):
        for msg in events.get(k, []):
            m.receive(msg)
            ev_lines.append(f"  {{{k}, {c_str(json.dumps(msg, separators=(',', ':')))}}},")
        fr = m.tick(k * TICK)
        frames.append(fr.copy())
        xs.append(float(m.x))
        gbs.append(int(m.gb))
        peaks.append(float(m.peak_ma))
        vs.append(float(m.v))
        drops.append(int(m.dropped))
        modes.append(1 if m.mode == "tick" else 0)
    # every tick: the frame's CRC-32 (zlib, the same function pova.h uses); full frames only at event ticks, the tick
    # after each event and every 10th tick, so a mismatch can be diagnosed pixel by pixel without a megabyte of vectors
    import zlib
    crcs = [zlib.crc32(f.tobytes()) & 0xFFFFFFFF for f in frames]
    keep = sorted({k for k in range(nticks) if k in events or (k - 1) in events or k % 10 == 0})
    text = f"// ---- session {name}: {nticks} ticks\n"
    text += f"static const VecCapEvent VEC_CAP_{name}_EVENTS[] = {{\n" + "\n".join(ev_lines) + "\n  {-1, 0}\n};\n"
    text += f"static const int VEC_CAP_{name}_TICKS = {nticks};\n"
    text += f"static const int VEC_CAP_{name}_MODE0 = {1 if mode == 'tick' else 0};\n"
    text += c_array(f"VEC_CAP_{name}_CRC", crcs, "uint32_t", 8, fmt=lambda v: f"0x{v:08X}u")
    text += f"static const int VEC_CAP_{name}_NKEEP = {len(keep)};\n"
    text += c_array(f"VEC_CAP_{name}_KEEP", keep, "int", 16)
    text += rle_block(f"VEC_CAP_{name}", [frames[k] for k in keep])
    text += c_array(f"VEC_CAP_{name}_X", xs, "double", 8, fmt=lambda v: repr(float(v)))
    text += c_array(f"VEC_CAP_{name}_V", vs, "double", 8, fmt=lambda v: repr(float(v)))
    text += c_array(f"VEC_CAP_{name}_GB", gbs, "uint8_t", 32)
    text += c_array(f"VEC_CAP_{name}_PEAK", peaks, "double", 8, fmt=lambda v: repr(float(v)))
    text += c_array(f"VEC_CAP_{name}_DROPPED", drops, "uint32_t", 32)
    text += c_array(f"VEC_CAP_{name}_TICKMODE", modes, "uint8_t", 32)
    return text


def gen_captions():
    text = HEAD + "struct VecCapEvent { int tick; const char* json; };\n"
    text += f"static const double VEC_CAP_TICK_S = {repr(TICK)};\n"
    text += f"static const double VEC_CAP_DEFAULT_CAP_MA = {Config().cap_ma!r};\n"
    # S1: word mode: short word, 5x7 word, a long word with the jump mini-scroll, a dim partial, clear
    s1 = {0: [{"cap": "word", "w": "HI"}], 6: [{"cap": "word", "w": "HELLO"}], 12: [{"cap": "word", "w": "TRANSCRIPTION"}],
          50: [{"cap": "word", "w": "HEL", "dim": 1}], 55: [{"cap": "clear"}], 57: [{"cap": "word", "w": "SO"}]}
    text += session("WORD", s1, 60)
    # S2: hybrid ticker (default): words arrive, each jumps in; partial; then 1.5 s of silence -> drift
    s2 = {0: [{"cap": "mode", "m": "tick"}, {"cap": "tick", "append": "CAPTIONS "}], 3: [{"cap": "tick", "append": "ON "}],
          5: [{"cap": "tick", "append": "THE "}], 9: [{"cap": "tick", "append": "COLUMN "}], 12: [{"cap": "tick", "append": "WHILE "}],
          20: [{"cap": "tick", "append": "I "}], 25: [{"cap": "tick", "append": "TALK "}], 27: [{"cap": "tick", "partial": "ABO"}],
          30: [{"cap": "tick", "append": "ABOUT ", "partial": ""}], 33: [{"cap": "tick", "append": "IT "}]}
    text += session("HYBRID", s2, 130)
    # S3: crawl ticker with a burst that forces drops, then a steady stream
    s3 = {0: [{"cap": "cfg", "tick_style": "crawl"}, {"cap": "mode", "m": "tick"}],
          1: [{"cap": "tick", "append": "A LONG BURST OF WORDS ARRIVES ALL AT ONCE "}]}
    for i, w in enumerate(["MORE", "WORDS", "KEEP", "COMING", "IN", "FAST", "NOW", "AND", "THEN", "STOP"]):
        s3[40 + 6 * i] = [{"cap": "tick", "append": w + " "}]
    text += session("CRAWL", s3, 160)
    # S4: current limiter on a white ticker all round the drum
    s4 = {0: [{"cap": "cfg", "rgb": [255, 255, 255]}, {"cap": "mode", "m": "tick"},
              {"cap": "tick", "append": "WWWWWWWWWWWWWWWWWWWWWWWWWWWWWWWWWW "}], 60: [{"cap": "clear"}]}
    text += session("LIMIT", s4, 90)
    # S5: cfg changes: colour, dim, vertical scale 1, smooth scroll; mode switch clears; word after a mode switch
    s5 = {0: [{"cap": "cfg", "rgb": [255, 0, 0], "dim": 0.5, "word_vs": 1, "scroll_style": "smooth"}],
          1: [{"cap": "word", "w": "TRANSCRIPTION"}], 31: [{"cap": "mode", "m": "word"}], 32: [{"cap": "word", "w": "HI"}],
          34: [{"cap": "word", "w": "HI", "dim": 1}]}
    text += session("CFG", s5, 36)
    write("vec_captions.h", text)


def main():
    gen_gamma()
    gen_povmap()
    # the parser fixture is the kit example (povgen/gen_dog_ball.py), built in memory: no animation file needed
    import tempfile
    from gen_dog_ball import build as _build_dog
    with tempfile.TemporaryDirectory() as _d:
        _p = os.path.join(_d, "dog_ball_orbit.pova")
        _build_dog("dog", "orbit").write(_p)
        with open(_p, "rb") as f:
            raw = f.read()
    dog = pa.Animation.from_bytes(raw)
    gen_current(dog)
    gen_pova(dog, raw)
    gen_font()
    gen_captions()


if __name__ == "__main__":
    main()
